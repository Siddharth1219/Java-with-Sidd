//                                      What is programming?
// Programming is the process of creating a set of instructions that tell a computer how to perform a task.
// Programming can be done using various programming languages, such as Java, Python, C++, and more.




//                           What is aLgorithm?    (a series of steps---->task performed)
// An algorithm is a step-by-step procedure or formula for solving a problem.
// It is a set of rules or instructions that are followed to achieve a specific outcome.



//                                      How to approach a problem?
// 1. Understand the problem: Read the problem statement carefully and identify the inputs, outputs, and constraints.
// 2. Break down the problem: Divide the problem into smaller, manageable parts or sub-problems.
// 3. Develop an algorithm: Create a step-by-step plan or algorithm to solve the problem.
// 4. Implement the algorithm: Write the code in a programming language to implement the algorithm.
// 5. Test and debug: Run the code with different test cases to ensure it works correctly and fix any errors or bugs that arise.
// 6. Optimize the solution: If necessary, improve the efficiency of the code or algorithm to make it run faster or use fewer resources.




//                                      What is a flowchart?
// A flowchart is a visual representation of a process or system, showing the sequence of steps and the decision points involved.



//                                      Components of a flowchart
// 1. Start/End: Represented by an oval shape, it indicates the beginning and end of the process.
// 2. Process: Represented by a rectangle, it indicates a step or action in the process.
// 3. Decision: Represented by a diamond shape, it indicates a point where a decision needs to be made, leading to different paths based on the outcome.
// 4. Input/Output: Represented by a parallelogram, it indicates the input or output of data in the process.
// 5. Arrows: Indicate the flow of the process.



//                                      What is pseudocode?
// Pseudocode is a high-level description of an algorithm or program that uses a combination of natural language and
// programming constructs to outline the logic and steps of a solution without adhering to the syntax of a specific programming language.



