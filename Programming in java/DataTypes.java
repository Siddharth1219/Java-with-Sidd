// ******************Non Primitive Data Types in Java******************


// 1. String: The String data type is used to represent a sequence of characters. It is not a primitive data type but rather a class in Java. Strings are used to store and manipulate text data.
// 2. Arrays: An array is a collection of elements of the same data type, stored in contiguous memory locations. It allows you to store multiple values in a single variable and access them using an index.
// 3. Classes and Objects: In Java, classes are used to define custom data types, and objects are instances of those classes. Classes can have fields (variables) and methods (functions) that define the behavior of the objects created from them.
// 4. Interfaces: An interface is a reference type in Java that defines a contract for classes to implement. It can contain method signatures and constants, but it cannot have any implementation. Classes that implement an interface must provide implementations for all its methods.
// 5. Enums: An enum (short for enumeration) is a special data type that represents a fixed set of constants. It is used to define a collection of related values, such as days of the week or colors. Enums provide type safety and can have methods and fields associated with them.
// 6. Collections: The Java Collections Framework provides a set of classes and interfaces for working with groups of objects. It includes data structures like lists, sets, and maps, which allow you to store and manipulate collections of data in a flexible and efficient manner.
// 7. Generics: Generics allow you to define classes, interfaces, and methods with type parameters. They enable you to create reusable code that can work with different data types while providing type safety at compile time. Generics are commonly used in the Java Collections Framework to create type-safe collections.