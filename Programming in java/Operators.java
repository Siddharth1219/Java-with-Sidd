// what is an operator in java?
// An operator in Java is a special symbol or keyword that is used to perform operations on variables and values.
//  Operators are used to manipulate data and perform various computations in Java programs. They can be categorized into several types, including:


// 1.Arithmetic Operators
// 2.Relational Operators
// 3.Logical Operators
// 4. Bitwise Operators
// 5. Assignment Operators
// 6. Unary Operators(Increment and Decrement Operators)






// ARITHMETIC OPERATORS IN JAVA
// Arithmetic operators are used to perform basic mathematical operations on numeric values. They include the following:

// Arithmetic Operators in Java:
// 1. Addition (+): Adds two operands.
// 2. Subtraction (-): Subtracts the second operand from the first.
// 3. Multiplication (*): Multiplies two operands.
// 4. Division (/): Divides the first operand by the second.
// 5. Modulus (%): Returns the remainder of the division of the first operand by the second.






// RELATIONAL OPERATORS IN JAVA
// Relational operators are used to compare two values and determine the relationship between them. They include the following:

// Relational Operators in Java:
// 1. Equal to (==): Returns true if the two operands are equal.
// 2. Not equal to (!=): Returns true if the two operands are not equal.
// 3. Greater than (>): Returns true if the first operand is greater than the second.
// 4. Less than (<): Returns true if the first operand is less than the second.
// 5. Greater than or equal to (>=): Returns true if the first operand is greater than or equal to the second.
// 6. Less than or equal to (<=): Returns true if the first operand is less than or equal to the second.






// LOGICAL OPERATORS IN JAVA
// Logical operators are used to combine multiple boolean expressions and return a boolean result. They include the following:

// Logical Operators in Java:
// 1. AND (&&): Returns true if both operands are true.
// 2. OR (||): Returns true if at least one of the operands is true
// 3. NOT (!): Returns true if the operand is false, and false if the operand is true.






// BITWISE OPERATORS IN JAVA
// Bitwise operators are used to perform operations on individual bits of integer values. They include the following:

// Bitwise Operators in Java:
// 1. AND (&): Performs a bitwise AND operation.
// 2. OR (|): Performs a bitwise OR operation.
// 3. XOR (^): Performs a bitwise exclusive OR operation.
// 4. Complement (~): Inverts the bits of the operand.
// 5. Left Shift (<<): Shifts the bits of the operand to the left, filling the rightmost bits with zeros.
// 6. Right Shift (>>): Shifts the bits of the operand to the right, filling the leftmost bits with the sign bit (for signed integers).
// 7. Unsigned Right Shift (>>>): Shifts the bits of the operand to the right, filling the leftmost bits with zeros (for unsigned integers).






// ASSIGNMENT OPERATORS IN JAVA
// Assignment operators are used to assign values to variables. They include the following: 

// Assignment Operators in Java:
// 1. Assignment (=): Assigns the value of the right operand to the left operand    
// 2. Addition Assignment (+=): Adds the right operand to the left operand and assigns the result to the left operand.
// 3. Subtraction Assignment (-=): Subtracts the right operand from the left operand and assigns the result to the left operand.
// 4. Multiplication Assignment (*=): Multiplies the left operand by the right operand and assigns the result to the left operand.
// 5. Division Assignment (/=): Divides the left operand by the right operand and assigns the result to the left operand.
// 6. Modulus Assignment (%=): Takes the modulus of the left operand by the right operand and assigns the result to the left operand.





// UNARY OPERATORS IN JAVA
// Unary operators are used to perform operations on a single operand. They include the following:  

// Unary Operators in Java:
// 1. Increment (++) : Increases the value of the operand by 1.
// 2. Decrement (--) : Decreases the value of the operand by 1.
// 3. Positive (+) : Returns the value of the operand.
// 4. Negative (-) : Returns the negation of the value of the operand.
// 5. Logical NOT (!) : Returns the negation of the boolean value of the operand.
// 6. Bitwise NOT (~) : Inverts the bits of the operand.