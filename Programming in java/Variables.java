
// variable is a container that holds data values.
// In Java, each variable must be declared with a specific data type.
//  The data type determines the size and layout of the variable's memory;
//  the range of values that can be stored within that memory;
//  and the set of operations that can be applied to the variable.






// ANY SPECIFIC RULES FOR VARIABLES NAMING?
// 1. Case Sensitive: Variable names are case-sensitive, meaning that "myVariable" and "myvariable" would be considered two different variables.
// 2. Start with a Letter, Underscore, or Dollar Sign: Variable names
// 3. Cannot be a Reserved Keyword: Variable names cannot be the same as Java reserved keywords (e.g., int, class, public).
// 4. No Spaces: Variable names cannot contain spaces. If you want to use multiple words, you can use camelCase (e.g., myVariableName) or underscores (e.g., my_variable_name).
// 5. Meaningful Names: It's a good practice to choose variable names that are descriptive and meaningful, so that the purpose of the variable is clear to anyone reading the code.






